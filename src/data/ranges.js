// The Central Mountain Range (Zhongyang Shanmo) runs like a long spine from the north-east tip of Taiwan
// down to the Hengchun peninsula. Built from its ridge line with a width that is greatest around Yushan.
function taiwanRidge() {
  const spine = [ // [lon, lat, half-width in degrees]
    [121.62, 25.00, 0.05], [121.52, 24.76, 0.12], [121.40, 24.50, 0.20], [121.30, 24.25, 0.26], [121.12, 23.95, 0.26],
    [121.02, 23.65, 0.27], [120.96, 23.35, 0.25], [120.90, 23.05, 0.21], [120.86, 22.75, 0.17], [120.84, 22.45, 0.12],
    [120.84, 22.15, 0.08], [120.84, 21.98, 0.04],
  ];
  const east = spine.map(([x, y, w]) => [+(x + w).toFixed(3), y]);
  const west = spine.map(([x, y, w]) => [+(x - w).toFixed(3), y]).reverse();
  return [...east, ...west];
}

